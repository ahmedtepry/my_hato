/// Arabic-first, fully bilingual (Arabic RTL / English LTR) strings.
/// Direction is handled automatically by MaterialApp + flutter_localizations.
const supportedLocales = [Locale('ar'), Locale('en')];

final sharedPrefsProvider = Provider<SharedPreferences>((_) => throw UnimplementedError('overridden in main'));

class LocaleController extends Notifier<Locale> {
  static const _key = 'app_locale';
  @override
  Locale build() {
    final saved = ref.read(sharedPrefsProvider).getString(_key);
    return Locale(saved == 'en' ? 'en' : 'ar');
  }

  Future<void> set(Locale l) async {
    state = l;
    await ref.read(sharedPrefsProvider).setString(_key, l.languageCode);
  }
}

final localeProvider = NotifierProvider<LocaleController, Locale>(LocaleController.new);

extension Tr on BuildContext {
  String get lang => Localizations.localeOf(this).languageCode;
  bool get isAr => lang == 'ar';
  String tr(String key, [Map<String, String> args = const {}]) {
    var s = (_strings[key]?[lang]) ?? _strings[key]?['ar'] ?? key;
    args.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }

  /// Picks the right column of a bilingual DB row: name_ar / name_en.
  String pick(Map<String, dynamic> row, String field) =>
      (row['${field}_$lang'] ?? row['${field}_ar'] ?? '').toString();
}

